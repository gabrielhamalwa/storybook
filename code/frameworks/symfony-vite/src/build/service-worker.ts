/**
 * Generates a Service Worker that:
 * 1. Loads php-cgi-wasm
 * 2. Loads the Symfony project archive into a virtual filesystem
 * 3. Boots the Symfony kernel
 * 4. Intercepts requests to /_storybook/* and /_live_component/*
 */

export interface ServiceWorkerOptions {
  /** URL path to the php-cgi-wasm runtime file. */
  phpWasmUrl: string;
  /** URL path to the Symfony project archive (.tar.gz). */
  projectArchiveUrl: string;
  /** Cache name for the service worker. */
  cacheName?: string;
}

export function generateServiceWorker(options: ServiceWorkerOptions): string {
  const { phpWasmUrl, projectArchiveUrl, cacheName = 'storybook-symfony-wasm' } = options;

  return `// Auto-generated by @storybook/symfony-vite
// This Service Worker runs PHP-WASM to render Symfony components in the browser.
const PHP_WASM_URL = ${JSON.stringify(phpWasmUrl)};
const PROJECT_ARCHIVE_URL = ${JSON.stringify(projectArchiveUrl)};
const CACHE_NAME = ${JSON.stringify(cacheName)};

let phpReady = null;
let phpInstance = null;

async function loadPhpWasm() {
  if (phpInstance) return phpInstance;

  importScripts(PHP_WASM_URL);
  const PHP = self.PHP;
  const php = await PHP.load('8.3', {
    requestHandler: {
      documentRoot: '/var/www',
      publicPath: '/var/www/public',
    },
  });

  // Load the project archive into the virtual filesystem
  const response = await fetch(PROJECT_ARCHIVE_URL);
  const archiveBuffer = await response.arrayBuffer();
  await php.writeFile('/tmp/project.tar.gz', new Uint8Array(archiveBuffer));
  await php.exec('tar', ['-xzf', '/tmp/project.tar.gz', '-C', '/var/www']);
  await php.unlink('/tmp/project.tar.gz');

  // Boot the Symfony kernel (warm the cache)
  await php.exec('php', [
    '/var/www/bin/console',
    'cache:warmup',
    '--env=storybook',
  ]);

  phpInstance = php;
  return php;
}

async function handleRequest(request) {
  const url = new URL(request.url);

  // Only intercept Storybook and Live Component requests
  if (!url.pathname.startsWith('/_storybook/') && !url.pathname.startsWith('/_live_component/')) {
    return fetch(request);
  }

  try {
    const php = await loadPhpWasm();

    const headers = {};
    request.headers.forEach((value, key) => {
      headers[key] = value;
    });

    const body = request.method !== 'GET' && request.method !== 'HEAD'
      ? await request.text()
      : '';

    const output = await php.run({
      method: request.method,
      url: url.pathname + url.search,
      headers,
      body,
    });

    return new Response(output.body, {
      status: output.status,
      headers: output.headers,
    });
  } catch (error) {
    return new Response(
      JSON.stringify({ error: 'PHP-WASM rendering failed', message: error.message }),
      { status: 500, headers: { 'Content-Type': 'application/json' } }
    );
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) =>
      cache.addAll([PHP_WASM_URL, PROJECT_ARCHIVE_URL])
    )
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', (event) => {
  event.respondWith(handleRequest(event.request));
});
`;
}

/**
 * Generates a script that registers the service worker from the main thread.
 */
export function generateServiceWorkerRegistration(swPath: string): string {
  return `
if ('serviceWorker' in navigator) {
  window.__STORYBOOK_SYMFONY_SW_READY__ = new Promise((resolve, reject) => {
    navigator.serviceWorker
      .register(${JSON.stringify(swPath)})
      .then((registration) => {
        const checkReady = () => {
          if (registration.active) {
            resolve(registration);
          } else {
            setTimeout(checkReady, 100);
          }
        };
        checkReady();
      })
      .catch(reject);
  });
}
`;
}
